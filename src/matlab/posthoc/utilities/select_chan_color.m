function cur_color = select_chan_color(ichan)

if ichan == 1
    cur_color = tableau_10('red');
elseif ichan == 2
    cur_color = tableau_10('blue');
elseif ichan == 3
    cur_color = tableau_10('orange');
elseif ichan == 4
    cur_color = tableau_10('purple');
elseif ichan == 5
    cur_color = tableau_10('pink');
elseif ichan == 6
    cur_color = tableau_10('green');
elseif ichan == 7
    cur_color = tableau_10('yellow');
elseif ichan == 8
    cur_color = tableau_10('brown');
end
